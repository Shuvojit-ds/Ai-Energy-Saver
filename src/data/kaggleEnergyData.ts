// Helper calculations for Kaggle analytics
export function getKaggleDatasetStatistics(records: KaggleRecord[] = KAGGLE_RAW_DATASET) {
  const totalCount = records.length;
  if (totalCount === 0) return { meanPower: 0, maxPower: 0, minPower: 0, avgTemp: 0, avgHumidity: 0, avgSub3Climate: 0 };

  const powers = records.map((r) => r.globalActivePowerKw);
  const temps = records.map((r) => r.temperatureC);
  const humidities = records.map((r) => r.humidityPct);
  const climates = records.map((r) => r.subMetering3ClimateWh);

  const meanPower = powers.reduce((a, b) => a + b, 0) / totalCount;
  const maxPower = Math.max(...powers);
  const minPower = Math.min(...powers);
  const avgTemp = temps.reduce((a, b) => a + b, 0) / totalCount;
  const avgHumidity = humidities.reduce((a, b) => a + b, 0) / totalCount;
  const avgSub3Climate = climates.reduce((a, b) => a + b, 0) / totalCount;

  return {
    totalCount,
    meanPower: Number(meanPower.toFixed(2)),
    maxPower: Number(maxPower.toFixed(2)),
    minPower: Number(minPower.toFixed(2)),
    avgTemp: Number(avgTemp.toFixed(1)),
    avgHumidity: Number(avgHumidity.toFixed(1)),
    avgSub3Climate: Number(avgSub3Climate.toFixed(0)),
  };
}

// Seasonal breakdown statistics
export function getSeasonalPowerAverages(records: KaggleRecord[] = KAGGLE_RAW_DATASET): Record<Season, { avgKw: number; count: number; avgTemp: number }> {
  const seasons: Season[] = ["Summer", "Monsoon", "Autumn", "Winter", "Spring"];
  const result: Record<Season, { avgKw: number; count: number; avgTemp: number }> = {
    Summer: { avgKw: 0, count: 0, avgTemp: 0 },
    Monsoon: { avgKw: 0, count: 0, avgTemp: 0 },
    Autumn: { avgKw: 0, count: 0, avgTemp: 0 },
    Winter: { avgKw: 0, count: 0, avgTemp: 0 },
    Spring: { avgKw: 0, count: 0, avgTemp: 0 },
  };

  for (const s of seasons) {
    const subset = records.filter((r) => r.season === s);
    if (subset.length > 0) {
      const avgKw = subset.reduce((acc, r) => acc + r.globalActivePowerKw, 0) / subset.length;
      const avgTemp = subset.reduce((acc, r) => acc + r.temperatureC, 0) / subset.length;
      result[s] = {
        avgKw: Number(avgKw.toFixed(2)),
        avgTemp: Number(avgTemp.toFixed(1)),
        count: subset.length,
      };
    }
  }

  return result;
}
